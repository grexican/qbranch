#!/usr/bin/env node
// One source, every platform. packages/<tool> (Claude Code plugin layout) is canonical; this script generates the rest:
// Every packages/<tool> folder is a complete standalone repo (published as its own read-only mirror), so all of
// this lands INSIDE the package:
//   dist/<tool>.mjs, dist/install.mjs     self-contained bundle + installer (plugin installs ship no node_modules)
//   adapters/{cursor,codex,gemini}/       native packages: manifest, hooks in the platform's format, skills, bundle
//   .claude-plugin/marketplace.json, .cursor-plugin/marketplace.json, .agents/plugins/marketplace.json
//   README.md install block               between the generated:install markers
// plus the monorepo's root marketplaces, which point into the packages.
// Usage: node scripts/sync.mjs [--check]   (--check: exit 1 if anything generated is stale; CI runs it)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';
import { parseFrontmatter } from '@qbranch/core';
import { TOOLS, hookEntries, mcpServers, renderHooks, renderMcp, checkSkill } from './platforms.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const files = new Map(); // repo-relative path -> content (string | Buffer)
const put = (p, c) => files.set(p.split(path.sep).join('/'), typeof c === 'string' || Buffer.isBuffer(c) ? c : JSON.stringify(c, null, 2) + '\n');
const rootPkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf8'));
const ORG = 'grexican'; // GitHub owner of the mirrors
const GENERATED = 'GENERATED by scripts/sync.mjs from packages/<tool>. Do not edit: change the canonical package and run `npm run sync`.';

// What each platform can do with a tool's hooks; derived from the same translation the adapters use.
const DROPPED = {
  UserPromptSubmit: 'per-prompt context (the platform cannot inject at prompt time)',
  SessionStart: 'session-start context', PostToolUse: 'post-call measurement and nudges', PreToolUse: 'pre-call guard',
};
const PLATFORM_NAMES = { claude: 'Claude Code', copilot: 'GitHub Copilot (CLI, VS Code)', cursor: 'Cursor', codex: 'OpenAI Codex', gemini: 'Gemini CLI', windsurf: 'Windsurf / Devin' };
function installDoc(tool, pkg, entries, servers) {
  const notes = JSON.parse(fs.readFileSync(path.join(pkg, 'package.json'), 'utf8')).platformNotes || {};
  const probe = (p) => (args) => ({ sh: args, ps: args });
  const rows = Object.entries(PLATFORM_NAMES).map(([p, name]) => {
    const kept = JSON.stringify(renderHooks(p, entries, probe(p)) || {});
    const lost = [...new Set(entries.filter(e => !kept.includes(e.args)).map(e => DROPPED[e.event]))];
    const bits = [];
    if (lost.length) bits.push(`no ${lost.join(', no ')}`);
    if (p === 'windsurf' && Object.keys(servers).length) bits.push('MCP server goes in your user-level mcp_config.json');
    if (notes[p]) bits.push(notes[p]);
    return `| ${name} | ${bits.length ? bits.join('; ') : 'everything'} |`;
  });
  return [
    '**Claude Code**: one marketplace for every Q Branch gadget; install only the ones you want.',
    '',
    '```bash',
    `claude plugin marketplace add ${ORG}/qbranch`,
    `claude plugin install ${tool}@qbranch        # add -s project to share it with your team`,
    '```',
    '',
    '**Any other agent**: one command from a clone (Node 22.13+). It copies the skills, merges the hooks and MCP config into the project, and is safe to re-run; `--uninstall` removes exactly what it added.',
    '',
    '```bash',
    `git clone https://github.com/${ORG}/qbranch`,
    `node qbranch/packages/${tool}/dist/install.mjs --platform cursor --project .   # or: claude, codex, gemini, copilot, windsurf`,
    '```',
    '',
    `Native packages are in [\`adapters/\`](adapters/): a Cursor plugin, a Codex plugin and a Gemini CLI extension. Copilot reads the Claude plugin marketplace directly. No Node on the machine? Use the \`qbranch\` native binary ([how](../../README.md#no-node-native-binary)).`,
    '',
    '| Platform | What works |',
    '|---|---|',
    ...rows,
  ].join('\n');
}

// "From Q Branch" footer: identical in every tool's README, so the gadgets link to each other.
function familyDoc(tool) {
  const rows = TOOLS.map(t => {
    const p = JSON.parse(fs.readFileSync(path.join(ROOT, 'packages', t, 'package.json'), 'utf8'));
    const name = t === tool ? `**${t}** (you are here)` : `[**${t}**](../${t})`;
    return `| ${name} | ${p.tagline || ''} |`;
  });
  return [
    `${tool} is a gadget from [Q Branch](../../README.md), the workshop where tools for AI agents get built and proven. The gadgets share a core and a release train, and each one installs and works on its own.`,
    '',
    '| Tool | |',
    '|---|---|',
    ...rows,
  ].join('\n');
}

function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => (e.isDirectory() ? walk(path.join(dir, e.name)) : [path.join(dir, e.name)]));
}

const errors = [];
const installer = (await esbuild.build({
  entryPoints: [path.join(ROOT, 'scripts', 'install.mjs')], bundle: true, platform: 'node', format: 'esm', target: 'node22',
  write: false, legalComments: 'none', logLevel: 'error', banner: { js: `// ${GENERATED}` },
})).outputFiles[0].text;
for (const tool of TOOLS) {
  const pkg = path.join(ROOT, 'packages', tool);
  const manifest = JSON.parse(fs.readFileSync(path.join(pkg, '.claude-plugin', 'plugin.json'), 'utf8'));

  // 1. skills must pass the agentskills.io spec: they are copied unchanged to every platform
  for (const d of fs.readdirSync(path.join(pkg, 'skills'))) {
    const { meta } = parseFrontmatter(fs.readFileSync(path.join(pkg, 'skills', d, 'SKILL.md'), 'utf8'));
    for (const e of checkSkill(path.join(pkg, 'skills', d), meta)) errors.push(`${tool}/skills/${d}: ${e}`);
  }

  // 2. the bundle
  const out = await esbuild.build({
    entryPoints: [path.join(pkg, 'bin', `${tool}.mjs`)], bundle: true, platform: 'node', format: 'esm', target: 'node22',
    write: false, legalComments: 'none', external: ['@huggingface/transformers'], logLevel: 'error',
    define: { __QBRANCH_VERSION__: JSON.stringify(rootPkg.version) }, // the plugin's own version, for the binary-skew note
    banner: { js: `// ${GENERATED}\nimport { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);` },
  });
  const bundle = out.outputFiles[0].text;
  put(`packages/${tool}/dist/${tool}.mjs`, bundle);
  put(`packages/${tool}/dist/install.mjs`, installer);

  // 3. native adapters
  const entries = hookEntries(pkg);
  const servers = mcpServers(pkg);
  const skillFiles = walk(path.join(pkg, 'skills')).map(f => [path.relative(pkg, f), fs.readFileSync(f)]);
  const adapter = (platform, rootVar, extra) => {
    const base = `packages/${tool}/adapters/${platform}`;
    for (const [rel, buf] of skillFiles) put(`${base}/${rel}`, buf);
    put(`${base}/dist/${tool}.mjs`, bundle);
    put(`${base}/README.md`, `# ${tool} for ${platform}\n\n${GENERATED}\n\n${manifest.description} See the [${tool} README](../../README.md).\n`);
    const node = (args) => ({ sh: `node "${rootVar}/dist/${tool}.mjs" ${args}`, ps: `node "${rootVar}/dist/${tool}.mjs" ${args}` });
    const hooks = renderHooks(platform, entries, node);
    if (hooks) put(`${base}/hooks/hooks.json`, hooks);
    const mcp = renderMcp(platform === 'codex' ? 'claude' : platform, servers, (args) => ({ command: 'node', args: [`${rootVar}/dist/${tool}.mjs`, ...args] }));
    extra(base, { hooks: !!hooks, mcp });
  };
  // per-package marketplaces: the mirror repo installs on its own
  const own = (source) => ({ name: tool, owner: { name: rootPkg.author }, metadata: { description: manifest.description, version: manifest.version },
    plugins: [{ name: tool, source, description: manifest.description, version: manifest.version }] });
  put(`packages/${tool}/.claude-plugin/marketplace.json`, own('./'));
  put(`packages/${tool}/.cursor-plugin/marketplace.json`, own('./adapters/cursor'));
  put(`packages/${tool}/.agents/plugins/marketplace.json`, own('./adapters/codex'));
  // README install block
  const readme = fs.readFileSync(path.join(pkg, 'README.md'), 'utf8');
  const block = /(<!-- generated:install[^>]*-->)[\s\S]*?(<!-- \/generated:install -->)/;
  if (!block.test(readme)) errors.push(`${tool}/README.md: missing <!-- generated:install --> ... <!-- /generated:install --> markers`);
  else {
    const fam = /(<!-- generated:family[^>]*-->)[\s\S]*?(<!-- \/generated:family -->)/;
    if (!fam.test(readme)) errors.push(`${tool}/README.md: missing <!-- generated:family --> ... <!-- /generated:family --> markers`);
    put(`packages/${tool}/README.md`, readme
      .replace(block, (m, a, b) => `${a}\n${installDoc(tool, pkg, entries, servers)}\n${b}`)
      .replace(fam, (m, a, b) => `${a}\n${familyDoc(tool)}\n${b}`));
  }
  const meta = { name: tool, description: manifest.description, version: manifest.version, author: manifest.author };
  adapter('cursor', '${CURSOR_PLUGIN_ROOT}', (base, has) => {
    if (has.mcp) put(`${base}/mcp.json`, has.mcp);
    put(`${base}/.cursor-plugin/plugin.json`, { ...meta, skills: './skills/', ...(has.hooks ? { hooks: './hooks/hooks.json' } : {}), ...(has.mcp ? { mcpServers: './mcp.json' } : {}) });
  });
  adapter('codex', '${PLUGIN_ROOT}', (base, has) => { // manifest keys per Codex plugin docs (skills/mcpServers keys UNVERIFIED)
    if (has.mcp) put(`${base}/.mcp.json`, has.mcp);
    put(`${base}/.codex-plugin/plugin.json`, { ...meta, skills: './skills/', ...(has.hooks ? { hooks: './hooks/hooks.json' } : {}), ...(has.mcp ? { mcpServers: './.mcp.json' } : {}) });
  });
  adapter('gemini', '${extensionPath}', (base, has) => {
    put(`${base}/gemini-extension.json`, { name: tool, version: manifest.version, description: manifest.description, ...(has.mcp ? { mcpServers: has.mcp.mcpServers } : {}) });
  });
}
if (errors.length) { console.error(`skill spec errors:\n  ${errors.join('\n  ')}`); process.exit(1); }

// 4. marketplaces
const owner = { name: rootPkg.author };
const plugins = (src) => TOOLS.map(t => {
  const m = JSON.parse(fs.readFileSync(path.join(ROOT, 'packages', t, '.claude-plugin', 'plugin.json'), 'utf8'));
  return { name: t, source: src(t), description: m.description, version: m.version };
});
const market = (src) => ({ name: rootPkg.name, owner, metadata: { description: rootPkg.description, version: rootPkg.version }, plugins: plugins(src) });
put('.claude-plugin/marketplace.json', market(t => `./packages/${t}`));
put('.cursor-plugin/marketplace.json', market(t => `./packages/${t}/adapters/cursor`));
put('.agents/plugins/marketplace.json', market(t => `./packages/${t}/adapters/codex`));

// 5. the storefront banner: Q's workbench, each gadget on the bench with a spec tag (icons are inlined: GitHub renders
// SVG as an image, which cannot load other files)
{
  const inner = (t) => fs.readFileSync(path.join(ROOT, 'packages', t, 'docs', `${t}-icon.svg`), 'utf8')
    .replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const spec = (t) => JSON.parse(fs.readFileSync(path.join(ROOT, 'packages', t, 'package.json'), 'utf8')).spec || '';
  const gadgets = TOOLS.map((t, i) => {
    const x = 70 + i * 272;
    return [
      `  <g transform="translate(${x} 0)">`,
      '    <ellipse cx="64" cy="262" rx="70" ry="9" fill="#14171C" opacity="0.55"/>',
      `    <g transform="translate(0 132)">${inner(t)}</g>`,
      '    <path d="M64 262 C 62 272 56 280 52 292" fill="none" stroke="#B9A57A" stroke-width="1.4"/>',
      '    <g transform="translate(40 286) rotate(-2.5)">',
      '      <path d="M0 8 L12 0 H170 V48 H12 L0 40 Z" fill="#E6D6B0" stroke="#B9A57A" stroke-width="1"/>',
      '      <circle cx="12" cy="24" r="3.2" fill="#2A2F37"/>',
      `      <text x="22" y="20" font-family="'Courier New', Courier, monospace" font-weight="700" font-size="13" fill="#2B2A26">${t}</text>`,
      `      <text x="22" y="38" font-family="'Courier New', Courier, monospace" font-size="10" fill="#4A463C">${spec(t)}</text>`,
      '    </g>',
      '  </g>',
    ].join('\n');
  });
  put('docs/qbranch.svg', [
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 352" width="1200" height="352" role="img" aria-labelledby="t d">',
    '  <title id="t">Q Branch</title>',
    `  <desc id="d">Q Branch, the workshop that equips agents, named for the gadget department in the James Bond films. On the workbench: ${TOOLS.join(', ')}, each with a spec tag. Generated by scripts/sync.mjs from the icons in packages/*/docs.</desc>`,
    '  <rect width="1200" height="352" fill="#22272E"/>',
    '  <!-- wall: riveted steel panels -->',
    '  <g stroke="#2C323B" stroke-width="2"><line x1="300" y1="0" x2="300" y2="268"/><line x1="600" y1="0" x2="600" y2="268"/><line x1="900" y1="0" x2="900" y2="268"/></g>',
    '  <g fill="#353C46"><circle cx="300" cy="14" r="3"/><circle cx="600" cy="14" r="3"/><circle cx="900" cy="14" r="3"/><circle cx="300" cy="254" r="3"/><circle cx="600" cy="254" r="3"/><circle cx="900" cy="254" r="3"/></g>',
    '  <!-- the lab sign -->',
    '  <rect x="430" y="26" width="340" height="74" rx="4" fill="#1A1E24" stroke="#3B4350" stroke-width="2"/>',
    `  <text x="600" y="72" text-anchor="middle" font-family="'Stencil', 'Bahnschrift', 'DIN Condensed', 'Arial Narrow', sans-serif" font-weight="700" font-size="40" letter-spacing="6" fill="#E9E4D8">Q BRANCH</text>`,
    `  <text x="600" y="92" text-anchor="middle" font-family="'Courier New', Courier, monospace" font-size="12" letter-spacing="2" fill="#9AA3AF">equipment for agents</text>`,
    '  <!-- the bench -->',
    '  <rect x="0" y="268" width="1200" height="16" fill="#5B636E"/>',
    '  <rect x="0" y="284" width="1200" height="68" fill="#3B4048"/>',
    '  <line x1="0" y1="269" x2="1200" y2="269" stroke="#8A939E" stroke-width="1.2"/>',
    ...gadgets,
    '</svg>',
    '',
  ].join('\n'));
}

// write or check
const stale = [];
for (const [rel, content] of files) {
  const f = path.join(ROOT, rel);
  const cur = fs.existsSync(f) ? fs.readFileSync(f) : null;
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (cur && cur.equals(next)) continue;
  stale.push(rel);
  if (!CHECK) { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, next); }
}
// orphans: generated files no longer produced
const genDirs = [path.join(ROOT, 'adapters'), ...TOOLS.map(t => path.join(ROOT, 'packages', t, 'adapters'))].filter(d => fs.existsSync(d));
const orphans = genDirs.flatMap(walk).map(f => path.relative(ROOT, f).split(path.sep).join('/')).filter(r => !files.has(r));
if (!CHECK) {
  for (const o of orphans) fs.rmSync(path.join(ROOT, o));
  if (fs.existsSync(path.join(ROOT, 'adapters'))) fs.rmSync(path.join(ROOT, 'adapters'), { recursive: true }); // pre-2026-10-15 layout
}
if (CHECK) {
  if (stale.length || orphans.length) { console.error(`generated files are stale (run npm run sync):\n  ${[...stale, ...orphans].join('\n  ')}`); process.exit(1); }
  console.log(`sync: ${files.size} generated files up to date`);
} else {
  console.log(`sync: ${files.size} generated files, ${stale.length} written, ${orphans.length} orphans removed`);
}
